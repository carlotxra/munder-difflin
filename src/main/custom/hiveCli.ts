/**
 * Installs the `hive` command line for god (T-054) and the prompt lines that
 * advertise it. Plan: docs/plans/orchestrator-alignment.md, Phase 4.
 *
 * Same pattern as the harness's own cth-hook shim and OpenCode plugin: the
 * script is embedded here and written into <hive>/bin at spawn, so packaging
 * (electron-builder.yml, an upstream file) is untouched. The logic lives in
 * hiveCliMain.ts as one self-contained function, serialised with toString().
 * Next to it, hive-cli.json carries the settings the script needs (spawn
 * toggle, ask-first clause, review and merge policy), rewritten at every god
 * spawn so it follows Settings.
 */
import { mkdirSync, writeFileSync, renameSync } from 'node:fs';
import { join } from 'node:path';
import type { OrchestratorLevers } from '../../shared/custom/orchestratorLevers';
import { hiveCliMain } from './hiveCliMain';

export const HIVE_CLI_FILE = 'hive-cli.cjs';

/** The script written to <hive>/bin/hive-cli.cjs. */
export function hiveCliSource(): string {
  return [
    '#!/usr/bin/env node',
    '// Generated by Munder Difflin (fork T-054, src/main/custom/hiveCliMain.ts). Do not edit: rewritten at every god spawn.',
    "'use strict';",
    `process.exitCode = (${hiveCliMain.toString()})(require, process, __dirname);`,
    ''
  ].join('\n');
}

export interface HiveCliSettings {
  godId: string;
  maySpawn: boolean;
  askFirstClause: string | null;
  doneClause: string;
  reviewPolicy: OrchestratorLevers['reviewPolicy'];
  autoMergeWhenGreen: boolean;
  integrationBranch: string;
}

const writeAtomic = (file: string, text: string): void => {
  const tmp = `${file}.${process.pid}.tmp`;
  writeFileSync(tmp, text, { encoding: 'utf8', mode: 0o755 });
  renameSync(tmp, file);
};

/** Write the script and its settings; returns the script path, or null on failure. */
export function installHiveCli(root: string, settings: HiveCliSettings): string | null {
  try {
    const bin = join(root, 'bin');
    mkdirSync(bin, { recursive: true });
    const file = join(bin, HIVE_CLI_FILE);
    writeAtomic(file, hiveCliSource());
    writeAtomic(join(bin, 'hive-cli.json'), JSON.stringify(settings, null, 2) + '\n');
    return file;
  } catch (e) {
    console.error('[hive] installHiveCli failed:', e);
    return null;
  }
}

/** Quote a path only when it needs it, so an allowlist prefix can match it. */
const q = (s: string): string => (/[\s"']/.test(s) ? `"${s.replace(/"/g, '\\"')}"` : s);

/** The "## Commands" section of god prompt V2. */
export function hiveCliPromptLines(node: string, cli: string, maySpawn: boolean): string[] {
  const run = `${q(node)} ${q(cli)}`;
  return [
    '## Commands',
    `Use these instead of writing the files by hand: each checks the details and refuses with a reason (exit 2) rather than guessing. Run them as \`${run} <command>\`; \`help\` lists every option.`,
    '- `roster`: who is on the floor, their state and their open cards.',
    '- `dispatch --to <agent> --task <id> --objective "..." --output "..." --boundaries "..." [--tools "..."] [--title "..."]`: sends the 4-part contract, adds the definition of done and the ASK FIRST clause, and sets the card to doing with the assignee.',
    '- `review --task <id> --to <agent> --branch <name> --sha <sha>`: sends a review to a different agent than the author.',
    '- `merge --task <id> --repo <path> --branch <name> --sha <sha> [--into <branch>] [--reviewed-by <agent>] [--human "<the human\'s yes>"]`: checks the branch tip is the reported SHA, that it fast-forwards, the review and the human\'s yes, then fast-forwards and marks the card done. Never pushes.',
    '- `ask --task <id> --q "<markdown>"`: checks the card shape (short, **bold** first sentence, listed options), adds it to humanQA and blocks the card.',
    '- `task add --id <id> --title "..." | task status <id> <todo|doing|blocked|done> | task done <id>`: never clears an assignee.',
    maySpawn ? '- `spawn --objective "..." --cwd <repo> [--none-fit]`: files a spawn request after showing who is already on the floor.' : null,
    'When a command refuses, follow its reason: it names the next step.'
  ].filter((l): l is string => l !== null);
}
